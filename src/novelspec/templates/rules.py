def rules_quality_standards() -> str:
    return """# 🎯 创作质量准则 — AI 必须遵循的核心规则

> 这些规则覆盖长篇小说的开篇、人设、剧情、节奏、世界观、情绪、文笔、底线、结尾全环节。
> AI 在创作、修改、审计时必须严格遵守。

---

## 一、开篇原则：3 章抓眼，7 章锁人，拒绝慢热劝退

### 1. 强钩子前置
开篇必须抛出悬念、冲突、危机、宿命感或强烈反差，不要大段景物描写、背景介绍、冗长独白。可以是生死危机、身份秘密、仇恨羁绊、逆天开局、命运反转，让读者第一时间产生"想知道后续"的欲望。

### 2. 信息轻量化铺垫
世界观、势力设定、人物背景随剧情自然带出，杜绝百科式堆砌设定。长篇最怕开篇"设定灌水"。

### 3. 快速立核心人设
主角的性格、目标、底线、困境，在前 3 章清晰展现，让读者快速代入主角，建立情感连接。

---

## 二、人设原则：立体鲜活，有成长弧光，拒绝工具人

### 1. 主角：共情为王，目标明确
- 要有清晰的核心诉求：生存、复仇、守护、逆袭、救赎、自由等，贯穿全书主线
- 不完美才真实：可以懦弱、偏执、冲动、有短板，杜绝圣母、无脑龙傲天、完美圣人等悬浮人设
- 长线成长弧光：从心性、能力、认知、格局全方位变化，长篇的核心魅力就是人物的蜕变

### 2. 配角：人人有动机，个个有记忆点
- 重要配角拥有独立背景、欲望、秘密与立场，不为衬托主角而存在
- 反派拒绝"纯粹坏"：有执念、苦衷、信仰、无奈，立场对立而非单纯善恶对立，高级反派是长篇出圈关键
- 精简工具人，功能性配角也要有小特点，避免路人脸同质化

### 3. 人物关系动态化
亲情、友情、爱情、敌对、利用、羁绊随剧情不断变化，没有一成不变的关系，增加剧情张力。

---

## 三、剧情原则：主线坚定，支线互补，逻辑自洽

### 1. 主线绝对清晰，贯穿全文
长篇最忌主线模糊、写着写着跑偏。所有支线、单元剧情，都要服务主线，或铺垫伏笔、或塑造人物、或推动格局升级。

### 2. 支线适量，松紧结合
用短支线、单元小故事丰富世界观、补充人设、缓解主线高压，但不能无限注水、无限水副本、水日常，避免读者疲劳弃书。

### 3. 伏笔预埋 + 回收闭环
- 长线伏笔：前期不经意的细节、对话、道具、秘密，中期发酵，后期引爆，是长篇耐读的核心
- 杜绝挖坑不填：冷门伏笔可以弱化，但关键伏笔、核心悬念必须完整回收，烂尾最大原因就是伏笔烂尾

### 4. 冲突层层升级，永不断层
冲突分等级：个人矛盾 → 团队矛盾 → 地域矛盾 → 势力矛盾 → 世界观终极矛盾，循序渐进，战力、格局、危机同步升级，杜绝战力崩坏、格局倒退。

---

## 四、节奏原则：张弛有度，高低起伏，杜绝平铺直叙

### 1. 经典节奏模板：紧张 — 缓冲 — 爆发
战斗/权谋/危机高压剧情之后，搭配日常、互动、情感、解谜缓冲；平缓铺垫后，立刻安排大事件、反转、团战、阴谋爆发，全程避免单调。

### 2. 控制章节信息量
每一章都要有小亮点：小反转、小突破、小悬念、小冲突，拒绝"一章全程对话、全程赶路、全程回忆"的无效水文。

### 3. 情绪节奏匹配读者期待
读者压抑久了给爽点，憋屈久了给反击，虐心之后给治愈，悬念之后给答案。长期压抑、全程憋屈、无反馈的剧情，极易流失读者。

---

## 五、世界观原则：设定统一，边界清晰，循序渐进拓展

### 1. 设定自洽，规则恒定
修炼体系、世界观法则、势力规则、科技/玄幻/都市底层逻辑一旦确定，绝不随意篡改。设定崩塌是长篇口碑崩盘的关键。

### 2. 世界观逐步解锁
从小地图到大世界，从浅层规则到深层秘辛，逐步拓展，让读者和主角一起探索，保持新鲜感。

### 3. 世界观服务故事，而非故事服务世界观
设定是为剧情、人物、冲突服务，不要为了炫设定强行增加复杂规则，增加阅读门槛。

---

## 六、情绪与共鸣原则：抓住人性，制造代入感与记忆点

### 1. 贴合大众底层人性诉求
无论题材（玄幻、都市、古言、悬疑、现实），都要贴合普通人的共鸣点：不甘平凡、渴望公平、守护所爱、反抗压迫、弥补遗憾、自我救赎。

### 2. 合理的爽感与虐感平衡
纯爽文容易审美疲劳，纯虐文读者难以坚持；爽点要有铺垫，虐点要有意义，逆袭、打脸、守护、重逢、和解，都是长效受欢迎的情绪点。

### 3. 情感描写克制且真挚
爱情、亲情、家国情怀、知己羁绊，不用刻意煽情，用行动、细节、抉择体现情感，远比直白抒情更有感染力。

---

## 七、叙事与文笔原则：通俗易懂，风格统一，细节落地

### 1. 文笔适配题材，拒绝过度炫技
大众向长篇优先简洁流畅、画面感强，华丽辞藻、晦涩修辞会拉高阅读门槛；悬疑偏细腻、权谋偏严谨、玄幻偏宏大，风格全程统一。

### 2. 细节落地，增强真实感
动作、心理、环境、对话细节到位，人物的抉择、行为符合自身性格与处境，避免行为割裂、言行不一。

### 3. 对话个性化
不同身份、性格、立场的角色，说话语气、用词、逻辑完全不同，通过对话就能区分人物，提升沉浸感。

---

## 八、核心底线原则：拒绝崩坏，守住口碑长线

### 1. 杜绝三大致命问题
人设崩坏（主角突然降智、反派强行降格）、战力/设定崩坏、剧情烂尾（强行完结、强行洗白、机械降神）。

### 2. 价值观正向且包容
不宣扬极端暴力、扭曲三观、无底线利己，主流正向价值观（善良、责任、坚守、成长）是作品长久传播的基础。

### 3. 保持创作连贯性
长篇创作周期长，需要提前搭建大纲、人物小传、时间线、伏笔清单，依靠框架约束创作，避免后期失控。

---

## 九、结尾原则：圆满留白，余味悠长

### 1. 主线彻底完结
终极矛盾、核心恩怨、世界观谜题全部解决，给读者完整的闭环体验。

### 2. 结局匹配故事基调
热血文终局恢弘，言情文终局圆满或释然，现实文终局写实，不强行 HE、不强行 BE。

### 3. 适度留白，拒绝画蛇添足
核心故事结束后，不用过度描写全员晚年、无限番外堆砌，留一点想象空间，提升作品格调。

---

## 核心铁律（一句话版）

> 开篇有钩子、人设能成长、剧情有主线、节奏有起伏、设定不崩塌、伏笔有回收、情绪有共鸣、结尾不烂尾。
"""
